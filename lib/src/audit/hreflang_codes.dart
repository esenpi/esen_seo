// Snapshot of the IANA Language Subtag Registry (2026-06-14).
// Google hreflang accepts ISO 639-1 languages, optional ISO 15924 scripts,
// and optional assigned ISO 3166-1 Alpha-2 regions.
// IANA's private and exceptional region subtags are intentionally omitted.

bool isValidHreflangCode(String value) {
  final normalized = value.toLowerCase();
  if (normalized == 'x-default') return true;
  final parts = normalized.split('-');
  if (parts.isEmpty || !_hreflangLanguages.contains(parts.first)) {
    return false;
  }
  var index = 1;
  if (index < parts.length && parts[index].length == 4) {
    if (!_hreflangScripts.contains(parts[index])) return false;
    index++;
  }
  if (index < parts.length) {
    if (!_hreflangRegions.contains(parts[index])) return false;
    index++;
  }
  return index == parts.length;
}

